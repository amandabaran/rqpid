#   ssh -o LogLevel=QUIET "$node" "sudo systemctl stop memcached 2>/dev/null || true; sudo systemctl disable memcached 2>/dev/null || true; sudo pkill -9 -x memcached 2>/dev/null || true"
#   echo "✓"
# done

# Cleanup temporary local map
rm -f "$HOSTS_FILE"

echo
echo "=== ✓ All keys synced and hosts updated successfully over the 10.10.1.x network! ==="